test('classifySensitive flags every real-world sensitive wording', () => {
  // Being flagged AT ALL is the safety property — the category only chooses
  // which sentence the sidebar shows. Asserted separately so that a wording
  // which reasonably belongs to two categories ("Do you hold a valid work
  // permit?" is both sponsorship and work authorization) can never be the
  // reason this test goes red and gets loosened.
  const missed = MUST_FLAG.filter(([, label]) => !m.classifySensitive(label))
                          .map(([, label]) => label);
  eq(missed.length, 0, `NOT FLAGGED:\n    ${missed.join('\n    ')}`);
});

test('classifySensitive assigns the expected category', () => {
  const wrong = [];
  for (const [expected, label] of MUST_FLAG) {
    const got = m.classifySensitive(label);
    if (got && got !== expected) wrong.push(`${label} -> ${got}, expected ${expected}`);
  }
  eq(wrong.length, 0, wrong.join('\n    '));
});

test('a question that is both sponsorship and authorization is still locked', () => {
  ok(m.classifySensitive('Do you hold a valid work permit?'));
  ok(m.classifySensitive('Do you have the right to work here without sponsorship?'));
});

test('classifySensitive leaves ordinary questions alone', () => {
  const flagged = [];
  for (const label of [
    'First name', 'Last name', 'Email address', 'Phone number',
    'LinkedIn profile', 'GitHub URL', 'Portfolio', 'City', 'State', 'Country',
    'Zip code', 'University', 'Degree', 'Major', 'Graduation date', 'GPA',
    'Current company', 'Current job title', 'Years of experience',
    'Notice period', 'When can you start?', 'Are you willing to relocate?',
    'How did you hear about us?', 'Why do you want to work here?',
    'Tell us about yourself', 'Do you agree to the terms and conditions?',
    'Would you like to receive marketing emails?', 'Key skills',
    'What is your preferred name?', 'Website',
  ]) {
    const got = m.classifySensitive(label);
    if (got) flagged.push(`${label} -> ${got}`);
  }
  eq(flagged.length, 0, `over-flagged:\n    ${flagged.join('\n    ')}`);
});

test('relocation is not treated as a sensitive question', () => {
  // It reads like an eligibility question but is a preference the user stated.
  eq(m.classifySensitive('Are you willing to relocate to New York?'), null);
});

