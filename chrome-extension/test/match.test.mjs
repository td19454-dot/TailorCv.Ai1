// ── similarity ───────────────────────────────────────────────

test('similarity handles the degenerate cases', () => {
  eq(m.similarity('abc', 'abc'), 1);
  eq(m.similarity('', ''), 1);
  eq(m.similarity('abc', ''), 0);
  eq(m.similarity(null, null), 1);
});

test('similarity agrees with Python difflib exactly', () => {
  // OPTION_MATCH_THRESHOLD (0.55) is a number tuned against
  // difflib.SequenceMatcher on the server side, so this implementation has to
  // BE that measure, not merely resemble it. The first version used a
  // longest-common-subsequence ratio and scored "canada" against "india" at
  // 0.55 where difflib says 0.18 — i.e. it turned "nothing fits, ask the user"
  // into a confident wrong answer.
  //
  // fixtures/difflib-ratios.json is generated by Python; regenerate with:
  //   python -c "import difflib,json; ..."  (see the file's provenance in git)
  const rows = JSON.parse(
    readFileSync(new URL('./fixtures/difflib-ratios.json', import.meta.url), 'utf8'));
  ok(rows.length > 300, `fixture too small: ${rows.length}`);
  const bad = [];
  for (const [a, b, expected] of rows) {
    const got = m.similarity(a, b);
    if (Math.abs(got - expected) > 1e-9) bad.push(`${a!==b?`${a} / ${b}`:a}: ${got} != ${expected}`);
  }
  eq(bad.length, 0, `${bad.length}/${rows.length} disagree:\n    ${bad.slice(0, 5).join('\n    ')}`);
});

test('similarity separates the adversarial near-misses difflib does', () => {
  ok(m.similarity('canada', 'india') < 0.3, 'unrelated words must score low');
  ok(m.similarity('india', 'indonesia') < m.similarity('austria', 'australia'));
});

