test('every sensitive FIELD_SYNONYMS entry is also caught by classifySensitive', () => {
  // Belt and braces: the two mechanisms are independent, and a synonym marked
  // sensitive that classifySensitive misses would be fillable by the LLM tier.
  const gaps = [];
  for (const entry of m.FIELD_SYNONYMS) {
    if (!entry.sensitive) continue;
    for (const label of entry.labels) {
      if (!m.classifySensitive(label)) gaps.push(`${entry.key}: ${label}`);
    }
  }
  eq(gaps.length, 0, `sensitive synonyms not flagged:\n    ${gaps.join('\n    ')}`);
});

test('no non-sensitive synonym is flagged sensitive', () => {
  // The inverse gap: a synonym NOT marked sensitive that classifySensitive
  // flags would be permanently unanswerable, since the deterministic tier
  // would refuse it and the LLM would never see it.
  const gaps = [];
  for (const entry of m.FIELD_SYNONYMS) {
    if (entry.sensitive) continue;
    for (const label of entry.labels) {
      const cat = m.classifySensitive(label);
      if (cat) gaps.push(`${entry.key}: "${label}" -> ${cat}`);
    }
  }
  eq(gaps.length, 0, `unanswerable synonyms:\n    ${gaps.join('\n    ')}`);
});

